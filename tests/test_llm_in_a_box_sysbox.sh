#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# test_llm_in_a_box_sysbox.sh — behavioral tests for the sysbox runtime's
# setup requirements and for a box damaged by a sysbox daemon restart.
#
# WHAT (no source grep — invariant 10):
#   SYS1: the installed sysbox-runc declares the `time` Linux namespace in
#         its `features` output. This is the property that decides whether
#         the runtime works on Docker 28+ (containerd 2.x).
#   SYS2: the launcher refuses to launch when fusermount3 is missing,
#         naming the package that provides it, and launches when it is
#         present.
#   SYS3: THE REPRODUCTION. A box is created, sudo works inside it, the
#         sysbox daemons are restarted, the box is stopped and started
#         again — and the launcher must refuse to attach to the damaged
#         box, naming the cause and the remedy.
#   SYS4: the remedy works (destroy + recreate restores a working box).
#         This is the positive control for SYS3: without it, a launcher
#         that refused EVERY box would pass SYS3.
#   SYS5: a healthy box is NOT reported as damaged, across a plain
#         stop/start cycle and a kill/start cycle. This pins that the
#         detection does not fire on the healthy path.
#   SYS6: a second start leaves /etc/passwd, /etc/group and
#         /etc/sudoers.d/agent byte-identical to the first start, and the
#         box's log carries no rename-failure line.
#   SYS7: property check — the box survives 2-6 start/stop cycles with the
#         user intact, the sudoers file correct and sudo working after
#         every cycle.
#   SYS8: a launch on the installed runtime succeeds with the current host
#         Docker (pins the documented combination, which is why no Docker
#         pin is needed).
#
# WHY: a sysbox box's files are owned by container id 0, which maps to an
#      unprivileged host id. Sysbox normally applies an ID-mapped mount so
#      host uid 0 appears as container uid 0; when that mount is absent,
#      host uid 0 falls outside the container's mapped range and the
#      kernel reports the overflow uid 65534 (nobody). sudo then refuses a
#      setuid binary it believes is owned by a non-root user:
#        sudo: /etc/sudo.conf is owned by uid 65534, should be 0
#        sudo: /usr/bin/sudo must be owned by uid 0 and have the setuid bit set
#      The damage is invisible until the box is restarted, so the user
#      meets it as a confusing sudo error deep inside the box. Restarting
#      the sysbox daemons wipes sysbox-fs's in-memory state for containers
#      that already exist (sysbox-fs logs "Received seccompNotifMsg
#      generated by unknown container"), and the box's next start comes up
#      without its ID mapping. The README itself tells operators to run
#      exactly that restart command, so this is reachable by following the
#      project's own instructions.
#
# THEORY OF THE DETECTION (SYS3/SYS5): the launcher compares ONE rootfs
#      file's owner as the box sees it against the host's view of the same
#      file through /proc/<pid>/root. On a healthy box the box sees uid 0;
#      on a damaged one it sees 65534 while the host still sees 0. The
#      comparison is a property of the running system, not of any source
#      or document (invariant 10). /etc/sudo.conf is compared because it
#      is stable across image changes and is the file the operator's error
#      message names.
#
# LLM-FRIENDLY NOTE: SYS1 and SYS8 need only the sysbox runtime and a
#   built sysbox image; SYS2 uses a PATH seam; SYS3-SYS7 create REAL
#   sysbox boxes and restart the REAL sysbox daemons, so they need root
#   (or sudo) on a host with sysbox installed. Everything skips
#   (skip-not-fail) when a prerequisite is absent, matching the project's
#   existing suites; the expectation is that they RUN where sysbox is
#   installed. Each box gets a private LLMBOX_STATE_DIR and a throwaway
#   project directory so the real ~/.llm-in-a-box and the real project
#   root are never touched.
#
#   The sudo checks use the NUMERIC uid:gid form of `docker exec -u`,
#   never the name form: on a box whose /etc/passwd cannot be resolved in
#   the outer daemon's context the name form fails with "unable to find
#   user", which would make a check pass or fail for the wrong reason.
# ---------------------------------------------------------------------------
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BOC="${LBX_BIN:-${SCRIPT_DIR}/../target/debug/lbx}"
export LLMBOX_SCRIPT_DIR="$SCRIPT_DIR/.."
SYSBOX_IMAGE="${LBX_TEST_SYSBOX_IMAGE:-llm-in-a-box:sysbox}"

PASS=0
FAIL=0
SKIP=0

check() {
    local description="$1"
    local condition="$2"
    if eval "$condition"; then
        echo "[PASS] $description"
        PASS=$((PASS + 1))
    else
        echo "[FAIL] $description"
        FAIL=$((FAIL + 1))
    fi
}

skip() {
    echo "[SKIP] $1"
    SKIP=$((SKIP + 1))
}

# ── Scratch directories ───────────────────────────────────────────────────
# Every box runs with a private state directory and its own project
# directory, so no check writes into the real ~/.llm-in-a-box or the real
# project root. The project directory is the working directory lbx is run
# from (it becomes the box's /data).
SYS_TMP="$(mktemp -d /tmp/llm-in-a-box-sysbox.XXXXXX)"
SYS_STATE="$SYS_TMP/state"
mkdir -p "$SYS_STATE"
export LLMBOX_STATE_DIR="$SYS_STATE"

cleanup() {
    # Remove any box this suite created, then the scratch tree. Failure is
    # tolerated: a check that already failed is the signal, not cleanup.
    docker rm -f sysbox-check-1 sysbox-check-2 >/dev/null 2>&1 || true
    # The per-session docker volumes the launcher mounts at /var/lib/docker.
    docker volume rm -f sysbox-check-1-docker sysbox-check-2-docker >/dev/null 2>&1 || true
    rm -rf "$SYS_TMP" 2>/dev/null || true
}
trap cleanup EXIT

# ── Prerequisite probes (skip-not-fail) ───────────────────────────────────
docker_ok() { docker info >/dev/null 2>&1; }
sysbox_runtime_ok() { docker info 2>/dev/null | grep >/dev/null 'sysbox-runc'; }
sysbox_image_ok() { docker image inspect "$SYSBOX_IMAGE" >/dev/null 2>&1; }

# How to run the sysbox daemon restart. Root is needed for systemctl; on a
# host where sudo is unavailable and we are not root, the daemon checks
# skip rather than fail.
can_restart_daemons() {
    [ "$(id -u)" = "0" ] && return 0
    command -v sudo >/dev/null 2>&1 && sudo -n true >/dev/null 2>&1
}
as_root() {
    if [ "$(id -u)" = "0" ]; then "$@"; else sudo -n "$@"; fi
}

# ── Box helpers ───────────────────────────────────────────────────────────
# Wait for the entrypoint to finish user setup. /tmp/.user-ready is written
# by entrypoint.sh once the box user exists, and is what lbx itself waits
# for before attaching.
wait_box_ready() {
    local name="$1" i
    for i in $(seq 1 90); do
        docker exec "$name" test -f /tmp/.user-ready >/dev/null 2>&1 && return 0
        sleep 1
    done
    return 1
}

# The box's own view of a file's owner (uid gid mode).
box_stat() {
    docker exec -u 0 "$1" stat -c '%u %g %a' "$2" 2>/dev/null | head -1
}

# The host's view of the same file, through the container's root mount.
# This is the comparison that proves whether an ID mapping is in effect:
# on a healthy box both agree (0 0 ...); on a damaged box the box reports
# the overflow uid 65534 while the host still reports 0.
host_stat() {
    local name="$1" path="$2" pid
    pid=$(docker inspect -f '{{.State.Pid}}' "$name" 2>/dev/null | head -1)
    [ -n "$pid" ] && [ "$pid" != "0" ] || return 1
    as_root stat -c '%u %g %a' "/proc/$pid/root$path" 2>/dev/null | head -1
}

# sudo inside the box, as the box user, using the NUMERIC form (see the
# LLM-FRIENDLY NOTE above).
box_sudo_works() {
    docker exec -u 1000:1000 "$1" sudo -n true >/dev/null 2>&1
}

# The launcher's own output for an attach/start attempt. Run from a
# throwaway project directory so /data is not the real project.
launch_box() {
    local name="$1" proj="$2"
    mkdir -p "$proj"
    ( cd "$proj" && "$BOC" --runtime sysbox "$name" 2>&1 < /dev/null )
}

# ── SYS1: the installed runtime declares the time namespace ───────────────
# Requirement SB3. THEORY: containerd 2.x (Docker 28+) asks the runtime
# which Linux namespaces it supports and strips any it does not declare.
# sysbox-runc 0.7.0 does not declare `time`, so containerd handles that
# namespace itself and mishandles the user namespace in the process, and
# every container create fails with
#   OCI runtime create failed: namespace {"time" ""} does not exist
# 0.7.1 declares `time` and works. Asserting the declaration is asserting
# the actual cause, not a version string: a build that declares `time`
# works regardless of how it is numbered. Reads the runtime's own output
# over the CLI (a running system), not a file (invariant 10).
if ! command -v sysbox-runc >/dev/null 2>&1; then
    skip "SYS1 installed sysbox-runc declares the time namespace (sysbox-runc not installed)"
else
    SYS1_NS="$(sysbox-runc features 2>/dev/null \
        | jq -r '(.linux.namespaces // []) | join(" ")' 2>/dev/null)"
    check "SYS1 installed sysbox-runc declares the time namespace (needed by Docker 28+/containerd 2.x)" \
        "printf '%s' \"\$SYS1_NS\" | grep -w >/dev/null time"
fi

# ── SYS2: fusermount3 is required and its absence is refused ──────────────
# Requirement SB5. THEORY: sysbox-fs is a FUSE filesystem and needs the
# fuse3 helper `fusermount3`, but the sysbox-ce package declares a
# dependency on `fuse` (version 2) only. Without the binary every create
# fails with "failed to pre-register with sysbox-fs" and sysbox-fs logs
# `exec: "fusermount3": executable file not found in $PATH`. The check
# drives the launcher with a PATH that hides fusermount3 and asserts it
# refuses with a message naming the package, then with the real PATH and
# asserts it does not refuse for that reason. A seam is used because the
# test host has fusermount3 installed (which is the desired state), so the
# missing case cannot otherwise be produced without damaging the host.
if ! docker_ok; then
    skip "SYS2 launcher refuses to launch without fusermount3 (docker unavailable)"
elif ! sysbox_runtime_ok; then
    skip "SYS2 launcher refuses to launch without fusermount3 (sysbox-runc runtime not registered)"
else
    SYS2_PROJ="$SYS_TMP/sys2-project"
    mkdir -p "$SYS2_PROJ"
    # A PATH with a directory holding everything except fusermount3: point
    # at the real PATH but shadow the binary with a directory that has no
    # such file. The launcher must detect the absence itself.
    SYS2_EMPTY="$SYS_TMP/empty-bin"
    mkdir -p "$SYS2_EMPTY"
    SYS2_OUT="$(
        cd "$SYS2_PROJ" \
        && PATH="$SYS2_EMPTY:$(dirname "$(command -v sysbox-runc)"):/usr/bin:/bin" \
           LBX_TEST_FUSERMOUNT3_MISSING=1 \
           "$BOC" --runtime sysbox sysbox-check-2 2>&1 < /dev/null
    )"
    SYS2_REFUSED="$(printf '%s' "$SYS2_OUT" | grep -iE >/dev/null 'fusermount3|fuse3' && echo yes || echo no)"
    docker rm -f sysbox-check-2 >/dev/null 2>&1 || true
    check "SYS2 launcher refuses to launch without fusermount3, naming the package that provides it" \
        "[ \"\$SYS2_REFUSED\" = yes ]"

    # Positive control: with the real PATH the launcher must NOT refuse for
    # this reason (it may still fail later for an unrelated reason, so the
    # assertion is only that the fusermount3 message is absent).
    SYS2_OUT_OK="$(
        cd "$SYS2_PROJ" \
        && "$BOC" --runtime sysbox --destroy sysbox-check-2 2>&1 < /dev/null || true
    )"
    SYS2_NOFALSE="$(printf '%s' "$SYS2_OUT_OK" | grep -iE >/dev/null 'fusermount3' && echo false || echo true)"
    check "SYS2 launcher does not report a missing fusermount3 when it is present" \
        "[ \"\$SYS2_NOFALSE\" = true ]"
fi

# ── SYS8: a launch works on the installed runtime with current Docker ─────
# Requirement SB4. THEORY: the Docker pin existed only to work around
# sysbox 0.7.0's missing `time` declaration. With a runtime that declares
# it, a box launches on a current host Docker. This is the positive
# control that makes "remove the pin" safe: it fails if the installed
# runtime cannot run on the host's Docker.
if ! docker_ok; then
    skip "SYS8 a sysbox box launches with the host's current Docker (docker unavailable)"
elif ! sysbox_runtime_ok; then
    skip "SYS8 a sysbox box launches with the host's current Docker (sysbox-runc runtime not registered)"
elif ! sysbox_image_ok; then
    skip "SYS8 a sysbox box launches with the host's current Docker ($SYSBOX_IMAGE not built)"
else
    docker rm -f sysbox-check-1 >/dev/null 2>&1 || true
    SYS8_PROJ="$SYS_TMP/sys8-project"
    SYS8_OUT="$(launch_box sysbox-check-1 "$SYS8_PROJ" | head -40)"
    SYS8_UP="$(docker ps --filter "name=^sysbox-check-1$" --format '{{.Names}}' 2>/dev/null)"
    check "SYS8 a sysbox box launches with the host's current Docker (no version pin needed)" \
        "[ \"\$SYS8_UP\" = sysbox-check-1 ]"
    docker rm -f sysbox-check-1 >/dev/null 2>&1 || true
fi

# ── SYS3-SYS7: real boxes, real daemon restarts ───────────────────────────
# Everything below needs a real box and the ability to restart the sysbox
# daemons. Skip-not-fail when any prerequisite is absent.
SYS3_READY=true
docker_ok            || SYS3_READY=false
sysbox_runtime_ok    || SYS3_READY=false
sysbox_image_ok      || SYS3_READY=false
can_restart_daemons  || SYS3_READY=false

if [ "$SYS3_READY" != true ]; then
    skip "SYS3 launcher refuses to attach to a box damaged by a sysbox daemon restart (needs docker + sysbox-runc + $SYSBOX_IMAGE + ability to restart the sysbox daemons)"
    skip "SYS4 the remedy (destroy + recreate) restores a working box (same prerequisites as SYS3)"
    skip "SYS5 a healthy box is not reported as damaged (same prerequisites as SYS3)"
    skip "SYS6 a second start does not re-run the user rename (same prerequisites as SYS3)"
    skip "SYS7 the box survives repeated start/stop cycles (same prerequisites as SYS3)"
else
    BOX=sysbox-check-1
    BOX2=sysbox-check-2
    PROJ="$SYS_TMP/box-project"
    PROJ2="$SYS_TMP/box2-project"
    mkdir -p "$PROJ" "$PROJ2"

    # ── Create the first box and establish the healthy baseline ───────────
    docker rm -f "$BOX" "$BOX2" >/dev/null 2>&1 || true
    launch_box "$BOX" "$PROJ" >"$SYS_TMP/sys3-create.log" 2>&1 || true
    BOX_READY=true
    wait_box_ready "$BOX" || BOX_READY=false

    if [ "$BOX_READY" != true ]; then
        # The box could not be created at all: that is a failure of the
        # runtime under test, not something to skip past silently.
        check "SYS3 launcher refuses to attach to a box damaged by a sysbox daemon restart (box did not become ready)" "false"
        skip "SYS4 the remedy (destroy + recreate) restores a working box (no box to work with)"
        skip "SYS5 a healthy box is not reported as damaged (no box to work with)"
        skip "SYS6 a second start does not re-run the user rename (no box to work with)"
        skip "SYS7 the box survives repeated start/stop cycles (no box to work with)"
    else
        # Precondition: on a healthy box sudo works and the box sees uid 0.
        # If this fails the rest of the suite cannot mean what it claims,
        # so it is reported as a failure with its own message.
        SYS_BASE_OK=false
        box_sudo_works "$BOX" && SYS_BASE_OK=true
        check "SYS3 precondition: sudo works inside a freshly created box" \
            "[ \"\$SYS_BASE_OK\" = true ]"

        BOX_SUDO_BEFORE="$(box_stat "$BOX" /etc/sudo.conf)"
        HOST_SUDO_BEFORE="$(host_stat "$BOX" /etc/sudo.conf)"

        # ── SYS6: capture the identity state of the first start ───────────
        docker exec -u 0 "$BOX" cat /etc/passwd >"$SYS_TMP/passwd.1" 2>/dev/null || true
        docker exec -u 0 "$BOX" cat /etc/group  >"$SYS_TMP/group.1"  2>/dev/null || true
        docker exec -u 0 "$BOX" cat /etc/sudoers.d/agent >"$SYS_TMP/sudoers.1" 2>/dev/null || true
        BOX_LOG_1="$(docker logs "$BOX" 2>&1 | grep -c 'usermod -l failed' || true)"

        # ── SYS5 (healthy half): a plain stop/start is not reported ───────
        docker stop "$BOX" >/dev/null 2>&1 || true
        SYS5_OUT_PLAIN="$(launch_box "$BOX" "$PROJ")"
        wait_box_ready "$BOX" >/dev/null 2>&1 || true
        SYS5_PLAIN_REFUSED="$(printf '%s' "$SYS5_OUT_PLAIN" | grep -iE >/dev/null 'damaged|65534|id.?mapping|owned by uid' && echo yes || echo no)"

        # ── SYS6: capture the second start and compare ───────────────────
        docker exec -u 0 "$BOX" cat /etc/passwd >"$SYS_TMP/passwd.2" 2>/dev/null || true
        docker exec -u 0 "$BOX" cat /etc/group  >"$SYS_TMP/group.2"  2>/dev/null || true
        docker exec -u 0 "$BOX" cat /etc/sudoers.d/agent >"$SYS_TMP/sudoers.2" 2>/dev/null || true
        BOX_LOG_2="$(docker logs "$BOX" 2>&1 | grep -c 'usermod -l failed' || true)"

        SYS6_IDENTICAL=true
        # Guard against a silent false failure: `cmp -s` on a MISSING file
        # exits non-zero, so a capture that failed to write (or a name
        # mismatch between the capture and the comparison) would be reported
        # as "the files differ" — the wrong reason. Require both files to be
        # non-empty before comparing. Measured 2026-10-11: an ad-hoc version
        # of this loop compared the wrong filenames and reported DIFFERS for
        # byte-identical files.
        for f in passwd group sudoers; do
            [ -s "$SYS_TMP/$f.1" ] && [ -s "$SYS_TMP/$f.2" ] || SYS6_IDENTICAL=false
            cmp -s "$SYS_TMP/$f.1" "$SYS_TMP/$f.2" || SYS6_IDENTICAL=false
        done
        check "SYS6 a second start leaves /etc/passwd, /etc/group and /etc/sudoers.d/agent byte-identical" \
            "[ \"\$SYS6_IDENTICAL\" = true ]"
        # The rename must not run again: no new failure line on the second
        # start. The first start may legitimately log none (the user did not
        # exist yet as the target), so the assertion is on the DELTA.
        check "SYS6 a second start logs no new user-rename failure" \
            "[ \"\$BOX_LOG_2\" -le \"\$BOX_LOG_1\" ]"

        # ── SYS5 (kill half): a kill/start cycle is not reported ─────────
        docker kill "$BOX" >/dev/null 2>&1 || true
        SYS5_OUT_KILL="$(launch_box "$BOX" "$PROJ")"
        wait_box_ready "$BOX" >/dev/null 2>&1 || true
        SYS5_KILL_REFUSED="$(printf '%s' "$SYS5_OUT_KILL" | grep -iE >/dev/null 'damaged|65534|id.?mapping|owned by uid' && echo yes || echo no)"
        SYS5_SUDO_OK=true
        box_sudo_works "$BOX" || SYS5_SUDO_OK=false
        check "SYS5 a healthy box is not reported as damaged after stop/start and kill/start cycles, and sudo still works" \
            "[ \"\$SYS5_PLAIN_REFUSED\" = no ] && [ \"\$SYS5_KILL_REFUSED\" = no ] && [ \"\$SYS5_SUDO_OK\" = true ]"

        # ── SYS3: THE REPRODUCTION ───────────────────────────────────────
        # Damage the box exactly as the README's own advice does: restart
        # the sysbox daemons while the box exists, then restart the box.
        as_root systemctl restart sysbox >/dev/null 2>&1 || true
        sleep 12
        # The damage is latent: sudo still works before the box restarts.
        SYS3_LATENT_OK=true
        box_sudo_works "$BOX" || SYS3_LATENT_OK=false

        docker stop "$BOX" >/dev/null 2>&1 || true
        SYS3_OUT="$(launch_box "$BOX" "$PROJ")"
        wait_box_ready "$BOX" >/dev/null 2>&1 || true

        # Ground truth: the box is actually damaged. Asserted directly from
        # the running system (the box's view vs the host's view), so the
        # launcher's verdict below cannot be right by accident.
        SYS3_BOX_STAT="$(box_stat "$BOX" /etc/sudo.conf)"
        SYS3_HOST_STAT="$(host_stat "$BOX" /etc/sudo.conf)"
        SYS3_ACTUALLY_DAMAGED=false
        case "$SYS3_BOX_STAT" in
            65534*) [ -n "$SYS3_HOST_STAT" ] && SYS3_ACTUALLY_DAMAGED=true ;;
        esac
        # sudo must be broken inside the damaged box; that is the user's
        # symptom and the reason the launcher must not hand over a terminal.
        SYS3_SUDO_BROKEN=false
        box_sudo_works "$BOX" || SYS3_SUDO_BROKEN=true

        check "SYS3 the reproduction damages the box (box sees uid 65534 while the host sees uid 0, and sudo fails inside)" \
            "[ \"\$SYS3_ACTUALLY_DAMAGED\" = true ] && [ \"\$SYS3_SUDO_BROKEN\" = true ]"

        # The launcher's verdict: it must refuse, name the cause, and give
        # the remedy. A silent attach is the bug.
        #
        # These three assertions must not match the launcher's NORMAL
        # output. A healthy launch prints "... — sysbox runtime; enables
        # bridged VM networking", so a bare /sysbox/ or /restart/ pattern
        # would pass on an undamaged box and prove nothing (verified: it
        # did). Each pattern therefore requires wording that only a
        # damage report can carry: the overflow uid, an explicit
        # "damaged" verdict, or the pairing of a daemon restart with the
        # box's lost ID mapping.
        SYS3_REFUSED="$(printf '%s' "$SYS3_OUT" \
            | grep -iE >/dev/null 'damaged|65534|id.?mapping|owned by uid' && echo yes || echo no)"
        # The cause: a daemon restart. Requires BOTH a daemon/restart word
        # AND that the sentence is about this box's damage, so the normal
        # "sysbox runtime" banner cannot satisfy it.
        SYS3_NAMES_CAUSE="$(printf '%s' "$SYS3_OUT" \
            | grep -iE >/dev/null '(daemon|sysbox-fs|sysbox-mgr)[^.]*(restart|restarted|terminated)|(restart|restarted)[^.]*(daemon|sysbox-fs|sysbox-mgr)' \
            && echo yes || echo no)"
        # The remedy: recreate. Requires the explicit action, not the word
        # "container" or "attach".
        SYS3_NAMES_REMEDY="$(printf '%s' "$SYS3_OUT" \
            | grep -iE >/dev/null 'destroy|recreate|re-create|create it again' && echo yes || echo no)"
        # The launcher must also not have handed over a terminal: it must
        # exit non-zero, which is what stops the user meeting the sudo
        # error inside the box.
        SYS3_EXIT="$(cd "$PROJ" && "$BOC" --runtime sysbox "$BOX" >/dev/null 2>&1 </dev/null; echo $?)"
        check "SYS3 launcher refuses to attach to a box damaged by a sysbox daemon restart" \
            "[ \"\$SYS3_REFUSED\" = yes ] && [ \"\$SYS3_EXIT\" != 0 ]"
        check "SYS3 the refusal names the cause (a sysbox daemon restart)" \
            "[ \"\$SYS3_NAMES_CAUSE\" = yes ]"
        check "SYS3 the refusal names the remedy (recreate the box)" \
            "[ \"\$SYS3_NAMES_REMEDY\" = yes ]"

        # ── SYS4: the remedy, and the positive control for SYS3 ───────────
        docker rm -f "$BOX" >/dev/null 2>&1 || true
        launch_box "$BOX" "$PROJ" >"$SYS_TMP/sys4-create.log" 2>&1 || true
        SYS4_READY=true
        wait_box_ready "$BOX" || SYS4_READY=false
        SYS4_SUDO=false
        [ "$SYS4_READY" = true ] && { box_sudo_works "$BOX" && SYS4_SUDO=true; }
        SYS4_STAT="$(box_stat "$BOX" /etc/sudo.conf)"
        # The launcher must NOT refuse a freshly recreated box: this is what
        # stops SYS3 passing on a launcher that refuses everything.
        SYS4_OUT="$(launch_box "$BOX" "$PROJ" 2>&1)"
        SYS4_REFUSED="$(printf '%s' "$SYS4_OUT" | grep -iE >/dev/null 'damaged|65534|id.?mapping|owned by uid' && echo yes || echo no)"
        check "SYS4 the remedy (destroy + recreate) restores a working box: sudo works and the box sees uid 0" \
            "[ \"\$SYS4_SUDO\" = true ] && [ \"\$SYS4_STAT\" = \"0 0 644\" ]"
        check "SYS4 the launcher does not report a freshly recreated box as damaged (positive control for SYS3)" \
            "[ \"\$SYS4_REFUSED\" = no ]"

        # ── SYS7: property check over repeated cycles ────────────────────
        # A printed seed makes a failure replayable. The property under test
        # is SB7's: the rename is IDEMPOTENT, so a start/stop cycle is a
        # no-op on the box's identity state.
        #
        # WHAT MAKES THIS RED (measured, not assumed): the rename bug does
        # NOT break the user, the sudoers file or sudo — those survive it
        # because the script's final existence check passes anyway. What the
        # bug produces is a spurious "usermod -l failed" line on every start
        # after the first. So the assertion that distinguishes fixed from
        # unfixed is the LOG DELTA per cycle, and the identity assertions
        # are regression pins (they must keep holding). A version of this
        # check that asserted only the identity state would pass on the
        # buggy code and prove nothing; that was measured on 2026-10-11 and
        # is why the delta is asserted first.
        SYS7_SEED="${LBX_TEST_SEED:-$RANDOM}"
        echo "SYS7 seed: $SYS7_SEED (replay with LBX_TEST_SEED=$SYS7_SEED)"
        SYS7_CYCLES=$(( (SYS7_SEED % 5) + 2 ))
        SYS7_NO_NEW_FAILURE=true
        SYS7_IDENTITY_OK=true
        SYS7_PREV_FAILS="$(docker logs "$BOX" 2>&1 | grep -c 'usermod -l failed' || true)"
        for i in $(seq 1 "$SYS7_CYCLES"); do
            docker stop "$BOX" >/dev/null 2>&1 || true
            launch_box "$BOX" "$PROJ" >/dev/null 2>&1 || true
